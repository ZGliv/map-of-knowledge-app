// Stage 1: scaffold a new place.
//
//   node scripts/generate/scaffold.mjs <id> --parent <nodeId> --key <key> --name "<Name>" --claim "<one sentence>"
//
// Adds the leaf to core/places.ts (so the map draws it), writes an empty bundle at
// src/places/generated/<id>.ts with the marked blocks the later stages fill, registers it, and
// mints the opaque IDs the check bank will need into content/generator/<id>/ids.json.
// The bundle fails validatePlace until it is drafted: that is the point.
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { args, bundleFile, ensure, logStage, ROOT, workDir, writeJson } from './lib.mjs';

const started = Date.now();
const a = args();
const id = a._[0];
const { parent, key, name, claim } = a;
if (!id || !parent || !key || !name || !claim) {
  console.error('usage: scaffold.mjs <id> --parent <nodeId> --key <key> --name "<Name>" --claim "<claim>"');
  process.exit(2);
}
if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(id) || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(key)) throw new Error('id and key are lowercase slugs');
if (parent.includes('.evolution')) throw new Error('Evolution is charted by hand (core/evolution.ts)');
if (!/^knowledge\.science\.biology\./.test(parent)) throw new Error('PLAN §13: no other realms before G4. Generated places stay inside Biology for now.');
if (existsSync(bundleFile(id))) throw new Error(`${id} already exists`);
const nodeId = `${parent}.${key}`;
const q = s => JSON.stringify(s).replace(/^"|"$/g, '').replace(/'/g, '\\\'');

// 1. The leaf on the map.
const placesFile = path.join(ROOT, 'src/core/places.ts');
const places = readFileSync(placesFile, 'utf8');
const marker = 'export const CHARTED_LEAVES: readonly ChartedLeaf[] = [\n';
if (!places.includes(marker)) throw new Error('core/places.ts has no CHARTED_LEAVES list');
writeFileSync(placesFile, places.replace(marker, `${marker}  { parent: '${parent}', key: '${key}', name: '${q(name)}', claim: '${q(claim)}', packId: '${id}' },\n`));

// 2. The empty bundle, with the blocks the deterministic stages own.
const camel = id.replace(/-(\w)/g, (_, c) => c.toUpperCase());
writeFileSync(bundleFile(id), `import type { PlaceBundle } from '../contract';

// ${name}. Generated by scripts/generate (see .claude/skills/generate-place/SKILL.md).
// Blocks between <generated:…> markers are written by scripts; everything else is drafted.

const NODE = '${nodeId}';

export const place: PlaceBundle = {
  schema: 'mok.place/2',
  id: '${id}',
  nodeId: NODE,
  pack: {
    id: '${id}',
    title: '${q(name)}',
    question: '',
    path: [],
    hue: 130,
    minutes: 9,
    media: {},
    beats: [],
    provenance: [],
  },
  reels: [],
  cases: [],
  bank: {
    node: NODE,
    title: '${q(name)}',
    claim: '${q(claim)}',
    pack: '${id}',
    expeditionFamilies: {},
    items: [],
  },
  transferOnlySources: [],
  // <generated:sources>
  sources: [],
  // </generated:sources>
  // <generated:mediaChecks>
  mediaChecks: [],
  // </generated:mediaChecks>
  // <generated:lineage>
  // </generated:lineage>
};
`);

// 3. Registered, so the registry, banks, deck and validator all see it.
const indexFile = path.join(ROOT, 'src/places/generated/index.ts');
let index = readFileSync(indexFile, 'utf8');
index = index.replace("import type { PlaceBundle } from '../contract';\n", `import type { PlaceBundle } from '../contract';\nimport { place as ${camel} } from './${id}';\n`);
index = index.replace('export const GENERATED_PLACES: readonly PlaceBundle[] = [\n', `export const GENERATED_PLACES: readonly PlaceBundle[] = [\n  ${camel},\n`);
writeFileSync(indexFile, index);

// 4. Opaque IDs for the bank (plan §8.2): never edit one once committed. A rerun (say, to put back
// the leaf and the registry line after a stopped draft) keeps the IDs and plan already minted.
const ALPHABET = '0123456789abcdefghjkmnpqrstvwxyz';
const mint = letter => `${letter}_${Array.from(randomBytes(10), byte => ALPHABET[byte & 31]).join('')}`;
ensure(workDir(id));
const idsFile = path.join(workDir(id), 'ids.json');
if (existsSync(idsFile)) console.log(`  kept the minted IDs in content/generator/${id}/ids.json`);
else writeJson(idsFile, {
  note: 'Item IDs pair with fresh family IDs; expedition families map the pack’s graded beats. Use each once.',
  items: Array.from({ length: 24 }, () => ({ item: mint('i'), family: mint('f') })),
  expeditionFamilies: Array.from({ length: 8 }, () => mint('f')),
});
const planFile = path.join(workDir(id), 'plan.json');
if (!existsSync(planFile)) writeJson(planFile, { id, nodeId, parent, key, name, claim, createdAt: new Date().toISOString() });

const minutes = logStage(id, 'scaffold', 'script', started);
console.log(`Scaffolded ${id} at ${nodeId} (${minutes} min).
  bundle:  src/places/generated/${id}.ts
  work:    content/generator/${id}/
Next: node scripts/generate/facts.mjs ${id} --wiki "<Article>" …`);
