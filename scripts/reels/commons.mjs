// Wikimedia Commons: what a file is, who made it and under which licence, read from the Commons API
// (imageinfo + extmetadata). Only the allowlist survives: public domain, CC0, CC BY and CC BY-SA.
// Never NC, ND, GFDL-only, unknown, files with "Restrictions", or anything filed as AI-generated.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { get } from './lib.mjs';

const FFMPEG = process.env.FFMPEG || '/opt/homebrew/bin/ffmpeg';

const API = 'https://commons.wikimedia.org/w/api.php?action=query&format=json&formatversion=2&prop=imageinfo&iiprop=url|extmetadata|size|mime&iiurlwidth=1280';

export const strip = html => String(html ?? '').replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#0?39;/g, "'").replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();

/** Commons metadata → the short licence name a reel prints, or null when it is not allowed. */
export function licenceOf(meta) {
  const code = String(meta?.License?.value ?? '').toLowerCase();
  const short = String(meta?.LicenseShortName?.value ?? '');
  if (/\bnc\b|-nc-|noncommercial|non-commercial|\bnd\b|-nd-|noderiv/i.test(`${code} ${short}`)) return null;
  let m = code.match(/^cc-by-sa-(\d\.\d)/); if (m) return ['2.0', '2.5', '3.0', '4.0'].includes(m[1]) ? `CC BY-SA ${m[1]}` : null;
  m = code.match(/^cc-by-(\d\.\d)/); if (m) return ['2.0', '2.5', '3.0', '4.0'].includes(m[1]) ? `CC BY ${m[1]}` : null;
  if (code === 'cc0' || /^CC0/.test(short)) return 'CC0';
  if (code === 'pd' || code.startsWith('pd-') || /^public domain$/i.test(short)) return 'Public domain';
  return null;
}

const AI = /\bAI[- ]generated\b|\bgenerated by (an )?AI\b|Midjourney|DALL[·-]?E|Stable Diffusion|\bAI-assisted\b|artificial intelligence generated/i;
/** Public domain on Commons, but someone (a museum, usually) claims copyright in the reproduction. */
const CLAIMED = /Items with copyright claims|third[- ]party copyright claim|Copyright claim by/i;

/** A Commons file page URL for a title like "File:Name.jpg". */
export const filePage = title => `https://commons.wikimedia.org/wiki/${encodeURI(title.replace(/ /g, '_')).replace(/\?/g, '%3F')}`;
/** "File:Name.jpg" from a page URL or a title in any spelling. */
export function fileTitle(pageOrTitle) {
  const raw = decodeURIComponent(String(pageOrTitle).replace(/^https:\/\/commons\.wikimedia\.org\/wiki\//, '')).replace(/_/g, ' ');
  return raw.startsWith('File:') ? raw : `File:${raw}`;
}

/** Commons hides a machine date ("+1450-00-00T00:00:00Z/7") in its HTML: never read it as text. */
const visible = html => String(html ?? '').replace(/<div[^>]*display:\s*none[^>]*>[\s\S]*?<\/div>/gi, '');

/** When a work was made, as Commons says it: "15th century", "c. 1654", "1906". Empty if unknown. */
export function whenOf(html) {
  const text = strip(visible(html));
  const century = text.match(/\b(\d{1,2})\s*(st|nd|rd|th)\s*[ -]?century\b/i);
  if (century) return `${century[1]}${century[2].toLowerCase()} century`;
  const range = text.match(/\bbetween\s+(1[0-9]{3}|20[0-9]{2})\s+and\s+(1[0-9]{3}|20[0-9]{2})\b/i);
  if (range) return `c. ${range[1]}–${range[2]}`;
  const year = text.match(/\b(1[0-9]{3}|20[0-9]{2})\b/);
  if (!year) return '';
  const circa = /\b(circa|ca\.?|c\.|about|around|probably)\s*$/i.test(text.slice(0, year.index).trim() + ' ') || /^(circa|ca\.?|c\.)/i.test(text);
  return `${circa ? 'c. ' : ''}${year[1]}`;
}

/** A clean, short attribution: the artist (first sentence, tags stripped), then when. */
export function creditOf(meta) {
  // Never a bare link as a name: drop URLs, then fall back to the credit line, then "Unknown author".
  const clean = html => strip(visible(html)).replace(/\bhttps?:\/\/\S+/g, '').replace(/\[\s*\d+\s*\]/g, '').replace(/^Gallery:.*$/i, '').replace(/^(See original (article|source)|US-gov|Aufnahme von)\b/i, m => /^Aufnahme von/i.test(m) ? '' : '').replace(/\s*\(talk\)\s*/gi, ' ').replace(/^Author:\s*/i, '').replace(/\s+,/g, ',').replace(/[\s,;:]+$/, '').trim();
  let artist = clean(meta?.Artist?.value);
  if (!artist || /^unknown/i.test(artist) || /^[\W\d]*$/.test(artist)) artist = clean(meta?.Credit?.value).replace(/^Own work$/i, '') || 'Unknown author';
  artist = artist.split(/\s*[\n;]\s*|\.\s+(?=[A-Z])/)[0].replace(/\s+/g, ' ').trim();
  if (artist.length > 70) artist = `${artist.slice(0, 67).replace(/\s+\S*$/, '')}…`;
  const when = whenOf(meta?.DateTimeOriginal?.value);
  return when && !artist.includes(when.replace(/^c\. /, '')) ? `${artist}, ${when}` : artist;
}

/** Everything the engine records about one file. */
export function describeFile(page) {
  const info = page?.imageinfo?.[0];
  if (!info) return { title: page?.title, missing: true };
  const meta = info.extmetadata ?? {};
  const categories = String(meta.Categories?.value ?? '');
  const description = strip(meta.ImageDescription?.value);
  return {
    title: page.title,
    page: filePage(page.title),
    // The 1280-wide thumbnail (Commons serves standard widths), tracking query stripped.
    src: (info.thumburl ?? info.url).replace(/\?.*$/, ''),
    original: info.url,
    width: info.width, height: info.height, mime: info.mime,
    license: licenceOf(meta),
    rawLicense: strip(meta.LicenseShortName?.value),
    author: strip(meta.Artist?.value) || 'unknown',
    credit: creditOf(meta),
    date: strip(meta.DateTimeOriginal?.value),
    description: description.slice(0, 1200),
    restrictions: String(meta.Restrictions?.value ?? '').split('|').map(s => s.trim()).filter(Boolean),
    aiGenerated: AI.test(categories) || AI.test(description),
    claimed: CLAIMED.test(categories),
    featured: /Featured pictures/i.test(categories) || /featured/i.test(String(meta.Assessments?.value ?? '')),
    quality: /Quality images/i.test(categories) || /quality/i.test(String(meta.Assessments?.value ?? '')),
  };
}

/** Allowed to appear in a reel: an allowlisted licence, no restrictions, not AI-made, a still image. */
export const usable = d => !!d && !d.missing && !!d.license && !d.restrictions.length && !d.aiGenerated && !d.claimed && /^image\/(jpeg|png|webp|tiff|svg\+xml)$/.test(d.mime ?? ''); // stills only: a GIF would animate

/** Look up files by title, 40 at a time. Returns title → description (missing ones marked). */
export async function filesInfo(titles, { ttlHours = 24 } = {}) {
  const out = new Map();
  const wanted = [...new Set(titles.map(fileTitle))];
  for (let i = 0; i < wanted.length; i += 40) {
    const batch = wanted.slice(i, i + 40);
    const data = await get(`${API}&titles=${encodeURIComponent(batch.join('|'))}`, { ttlHours });
    const normalized = new Map((data?.query?.normalized ?? []).map(n => [n.to, n.from]));
    for (const page of data?.query?.pages ?? []) {
      const d = describeFile(page);
      out.set(page.title, d);
      if (normalized.has(page.title)) out.set(normalized.get(page.title), d);
    }
  }
  return out;
}

/** The licence snapshot a reel's validator reads (explore/validate.ts EngineMediaCheck). */
export const snapshotOf = d => ({ page: d.page, license: d.license ?? d.rawLicense, restrictions: d.restrictions, aiGenerated: d.aiGenerated, width: d.width, height: d.height, checkedAt: new Date().toISOString() });

/** How a PNG reads on the reel's near-black stage, measured with ffmpeg: the share of it that is
 * opaque, and its brightness laid over black. Dark line art on a transparent background (how Commons
 * renders most SVGs) all but disappears there: it `vanishes`. */
export function measureOnDark(file) {
  const average = filters => Number(/YAVG=([\d.]+)/.exec(execFileSync(FFMPEG, ['-v', 'error', '-i', file, '-vf', `${filters},signalstats,metadata=print:key=lavfi.signalstats.YAVG:file=-`, '-f', 'null', '-'], { encoding: 'utf8' }))?.[1] ?? NaN) / 255;
  const opaque = average('format=rgba,alphaextract');
  const onBlack = average('format=rgba,premultiply=inplace=1,format=gray');
  return { vanishes: opaque < 0.7 && onBlack < 0.15, opaque, onBlack };
}

/** The same for a reel's image URL. JPEGs have no transparency and never vanish. */
export async function onDark(src) {
  if (!/\.png$/i.test(new URL(src).pathname)) return { vanishes: false };
  const file = path.join(tmpdir(), `mok-reel-${createHash('sha256').update(src).digest('hex').slice(0, 16)}.png`);
  if (!existsSync(file)) writeFileSync(file, await get(src, { as: 'bytes', ttlHours: 24 * 30 }));
  return measureOnDark(file);
}
